"""P2 - migrate the legacy markdown registers into the canonical item store.

Standard: ISA_Engineering_Rules.md (referenced by rule id, never restated).
Spec:     ISA_BuildSpec_ItemRegister_4C_09Aug2026.md  s6 (migration), s9 (P2).

WHAT THIS IS
------------
Three markdown registers held the framework's open work. The moment a second register
exists, one of them starts lying (ISA-0025). This module moves them into
Dashboard/state/isa_items.jsonl and leaves them as renders.

THE DISCIPLINE, AND WHY IT IS THE WHOLE DESIGN
----------------------------------------------
Spec s6.3(a): migration is MECHANICAL EXTRACTION PLUS EXPLICIT MISSING, never
interpretation. A one-pass reading of 1,500 lines of narrative is exactly the
plausible-but-wrong artefact this register exists to catch.

So:
  * every item-shaped row and heading in the three sources is EXTRACTED (never
    hand-typed), with its verbatim text carried into `narrative`;
  * every extracted candidate must be resolved by a DECLARATION - MIGRATE, ALIAS
    (already in the store) or EXCLUDE (with a reason). An unresolved candidate
    RAISES (R4.9: a reader that cannot match a row counts it and fails);
  * the declaration states how many occurrences it expects. A source edit that adds
    or removes an occurrence FAILS the migration rather than silently re-reading it
    (R5.2 - two independent derivations of the same fact must agree);
  * fields the text does not literally yield are left absent, never inferred
    (R7.5, R4.1). `provenance` is `backfilled` on every migrated record and trend
    metrics start Sep-2026.

COLLISIONS ARE THE POINT
------------------------
The sources carry four unrelated `D-` schemes and two different `D1`s in ONE file
(X-Ray staleness at line 484, Artemis SmartGARP at line 1167). Legacy ids are
therefore NEVER used as store ids; each maps through isa_id_map.json qualified by
source (R7.6). A declaration whose id denotes more than one item declares each
definition line explicitly, so a merge cannot happen by accident.

CLI:
  python3 isa_register_migrate.py --extract          # candidate report, writes nothing
  python3 isa_register_migrate.py --plan             # resolve against declarations
  python3 isa_register_migrate.py --apply            # write to the store
  python3 isa_register_migrate.py --reconcile        # P2 gate (spec s9)
  python3 isa_register_migrate.py --selftest

Stdlib only. Imports isa_register (the only writer) and NO Dashboard module.
"""
